#!/usr/bin/env python3
"""Collect CJK characters used by source files and check LVGL font coverage.

Usage:
    python tools/check_fonts.py --collect src/dev
    python tools/check_fonts.py --src src/dev --font src/fonts/ui_font_syhtm18.c

LVGL fonts generated by lv_font_conv contain comments like::

    /* U+4E2D "中" */

We use those comments as the authoritative glyph list. If a font has no such
comments, the check is skipped with a warning instead of producing a false
failure.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CJK_RE = re.compile(
    r"[㐀-䶿一-鿿豈-﫿　-〿＀-￯]"
)
COMMENT_RE = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
GLYPH_COMMENT_RE = re.compile(r"/\*\s*U\+([0-9A-Fa-f]{4,6})")

SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".h", ".hpp"}


def strip_comments(text: str) -> str:
    return COMMENT_RE.sub("", text)


def collect_from_file(path: Path) -> set[str]:
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        text = path.read_text(encoding="utf-8", errors="replace")
    return set(CJK_RE.findall(strip_comments(text)))


def collect_from_paths(paths: list[Path]) -> dict[str, set[Path]]:
    used: dict[str, set[Path]] = {}
    for root in paths:
        if not root.exists():
            continue
        files = [root] if root.is_file() else [
            p for p in root.rglob("*") if p.suffix.lower() in SOURCE_SUFFIXES
        ]
        for path in files:
            if path.name.startswith("font_") or path.name.startswith("ui_font_"):
                continue
            for char in collect_from_file(path):
                used.setdefault(char, set()).add(path)
    return used


def parse_font(path: Path) -> tuple[set[str], bool]:
    text = path.read_text(encoding="utf-8", errors="replace")
    codepoints = {chr(int(m, 16)) for m in GLYPH_COMMENT_RE.findall(text)}
    return codepoints, bool(codepoints)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--src",
        nargs="+",
        default=["src/dev"],
        help="source files/directories to scan (default: src/dev)",
    )
    parser.add_argument(
        "--font",
        nargs="+",
        default=[],
        help="generated LVGL font .c files",
    )
    parser.add_argument(
        "--collect",
        action="store_true",
        help="only print used characters and exit",
    )
    args = parser.parse_args()

    src_paths = [Path(p) if Path(p).is_absolute() else Path.cwd() / p for p in args.src]
    used = collect_from_paths(src_paths)

    if not used:
        print("[OK] no CJK characters found in scanned sources")
        return 0

    chars = "".join(sorted(used))
    print(f"used CJK characters: {len(used)}")
    print(chars)

    if args.collect:
        return 0

    if not args.font:
        print(
            "[FAIL] CJK text found but no --font was provided; "
            "generate a subset font (see docs/fonts.md)"
        )
        return 1

    covered: set[str] = set()
    for item in args.font:
        path = Path(item) if Path(item).is_absolute() else Path.cwd() / item
        if not path.exists():
            print(f"[FAIL] font not found: {path}")
            return 1
        glyphs, parsed = parse_font(path)
        if not parsed:
            print(f"[WARN] cannot parse glyph comments from {path}; skipping coverage")
            return 0
        covered |= glyphs

    missing = sorted(set(used) - covered)
    if missing:
        print(f"[FAIL] {len(missing)} character(s) missing from font:")
        for char in missing:
            files = ", ".join(str(p) for p in sorted(used[char]))
            print(f"  {char}  U+{ord(char):04X}  ({files})")
        return 1

    print(f"[OK] all {len(used)} CJK characters covered by provided font(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
